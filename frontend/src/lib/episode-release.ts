export type EpisodeSection = 'review' | 'audio' | 'delivery' | 'metadata' | 'publication' | 'backup';

export interface EpisodeScheduleItem extends Record<string, unknown> {
  episode_id: string;
  type: string;
  state?: string;
  scheduled_date?: string;
  destination?: string;
  destinations?: string[];
  clip_id?: string;
  job_id?: string;
  request_id?: string;
  error?: string;
  artifact_current?: boolean | null;
}

export interface EpisodePublicationEvidence extends Record<string, unknown> {
  episode_id: string;
  content_type: string;
  status: string;
  destination?: string;
  destinations?: string[];
  clip_id?: string;
  url?: string;
  scheduled?: boolean;
  job_id?: string;
  request_id?: string;
  error?: string;
}

export interface EpisodeScheduleProjection {
  loaded: boolean;
  items: EpisodeScheduleItem[];
  publicationEvidence: EpisodePublicationEvidence[];
  blockers: string[];
}

